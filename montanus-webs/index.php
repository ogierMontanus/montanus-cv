					<h1 class="headline">F.E.S. Thüringen</h1>
		
		<h2>Die FES-Thüringen stellt sich vor</h2>
<p><img class="size-full wp-image-40 alignleft" src="https://www.fes-thueringen.de/wp-content/uploads/sites/39/2020/09/fledermaus.png" alt="" width="100" height="50" /><img class="size-medium wp-image-41 alignright" src="https://www.fes-thueringen.de/wp-content/uploads/sites/39/2020/09/vampire-300x230.png" alt="" width="300" height="230" srcset="https://www.fes-thueringen.de/wp-content/uploads/sites/39/2020/09/vampire-300x230.png 300w, https://www.fes-thueringen.de/wp-content/uploads/sites/39/2020/09/vampire.png 595w" sizes="(max-width: 300px) 100vw, 300px" />Wir sind ein kleiner Club von Interessenten aus dem schönen Raume Thüringens, die sich bereits seit Jahren für ungewöhnliche Mythengestalten aus dem Raum Sachen interessieren. Seit 1998 gehen wir unser Hobby einmal monatlich in unserem Stammlokal nach und treffen uns zum Austausch mit anderen Mitgliedern, um die Faszination des Unbekannten bei fröhlichen Umtrunken untereinander auszutauschen.</p>
<hr />
<h3>Wie sieht die Arbeit des FES-Thüringen genau aus?</h3>
<p><img class="size-medium wp-image-39 alignleft" src="https://www.fes-thueringen.de/wp-content/uploads/sites/39/2020/09/werewolf-300x225.jpg" alt="" width="300" height="225" srcset="https://www.fes-thueringen.de/wp-content/uploads/sites/39/2020/09/werewolf-300x225.jpg 300w, https://www.fes-thueringen.de/wp-content/uploads/sites/39/2020/09/werewolf-768x576.jpg 768w, https://www.fes-thueringen.de/wp-content/uploads/sites/39/2020/09/werewolf.jpg 960w" sizes="(max-width: 300px) 100vw, 300px" />Wenn wir ein interessantes Themengebiet entdeckt haben, stürzen sich unsere freiwilligen Forscher direkt darauf und recherchieren was das Zeug hält. Dabei kann es sich um merkwürdige Bigfoot-Sichtungen oder sogar UFO-Begegnungen handeln. Wir hatten auch schon Erfahrungen mit Poltergeistern aller Art und natürlichen dämonischen Ritualen, Zwergen, Kobolden, Trollen, Fischwesen und Untoten. Falls ihr eine Sichtung gemacht habt solltet ihr deshalb nicht zögern, sie uns mitzuteilen.</p>
<p>Wir befassen uns aber auch generell mit allen Paranormalen-Phänomen der Welt, dazu zählen Nahtodbegegnungen oder außerkörperliche Erfahrungen und sogar Telekinese oder Telepathie, Wünschelruten und Hexenspiele, Dämonenaustreibungen oder Fernwahrnehmungen und noch vieles mehr. Es lohnt sich deshalb uns unbedingt langfristig zu folgen, damit ihr keine der spannenden Erfahrungsberichte unseres Teams verpasst. Schaut auch in unsere speziellen Rubriken hinein, denn dort beschäftigen für uns außerdem mit etlichen Sagengestalten aus dem Raum Sachsen aber auch Thüringen.</p>
<p><img class="size-full wp-image-40 alignright" src="https://www.fes-thueringen.de/wp-content/uploads/sites/39/2020/09/fledermaus.png" alt="" width="100" height="50" /><img class="size-medium wp-image-53 alignleft" src="https://www.fes-thueringen.de/wp-content/uploads/sites/39/2020/09/ufos-am-himmel-300x212.png" alt="" width="300" height="212" srcset="https://www.fes-thueringen.de/wp-content/uploads/sites/39/2020/09/ufos-am-himmel-300x212.png 300w, https://www.fes-thueringen.de/wp-content/uploads/sites/39/2020/09/ufos-am-himmel-768x543.png 768w, https://www.fes-thueringen.de/wp-content/uploads/sites/39/2020/09/ufos-am-himmel.png 960w" sizes="(max-width: 300px) 100vw, 300px" />Wir erklären, woher der Mythos stammt und beobachten, ob er vielleicht einen wahren Kern hat, denn nicht hinter jedem Monster steckt etwas Ungewöhnliches. Vielfach entpuppen sich Sichtungen als herkömmliche Phänomene, die sich schnell erklären lassen. So steigen im Sommer gerne Himmellaternen von Zusammenkünften an Taufen und anderen Partys hinauf. Sie sorgen für ein Spektakel der anderen Art und werden von manchen Zeugen als Raumschiffe aus dem All gedeutet. Unsere Augen spielen uns des Öfteren einen Streich, deshalb ist es wichtig, Wahrheit von Fiktion trennen zu können.</p>
<p>Jetzt wünschen wir euch selbstverständlich viel Spaß und Freude auf unserer eigenen Homepage, beim Herumstöbern durch die einzelnen Artikel und wir würden uns freuen, wenn ihr uns selbst einmal eure Gedanken mitteilen würdet. Bis bald, eure FES Thüringen.</p>

		
		
