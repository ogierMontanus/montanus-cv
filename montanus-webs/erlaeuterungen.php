<h3 align="center">Das „Diarium Actorum“ des Caspar Heinrich Marx</h3>
<h4 align="center">Holger Berg (Kopenhagen)</h4>


<p align="justify">Als zwei Geistliche am 27. November 1629 zum Doktor der Theologie
promovierten, war es ein großer Tag für die katholische Gemeinschaft in Erfurt.
Solches war „in 110 Jahren nicht geschehen“ gab ein Beobachter aus der
lutherischen Mehrheit widerwillig zu; eine theologische Promotion hatte zuletzt
1520 stattgefunden, vor der städtischen Reformation.<a name="_Ref163471535"></a><a
href="#_edn1" name="_ednref1" >[1]</a> Hierin sahen
sowohl der lutherische Chronikschreiber wie auch die katholischen Teilnehmer
eine feierliche, zeremonielle Bestätigung, dass der Katholizismus vor Ort
wieder erstarkt war. Im Laufe der vergangenen zwanzig Jahre hatte die bis dahin
seit Jahrzehnten dahinsiechende Glaubensgemeinschaft einen Aufschwung genommen;
nun konnte sie die Hoffnung haben, sich gegen die lutherischen Häretiker zu
behaupten. Verantwortlich für diese Vitalisierung war hauptsächlich die Mission
des jungen Ordens der Jesuiten. 1611 gründeten die Jesuiten eine Schule in
Erfurt, welche sie bis zum Jahre 1616 zu einem Gymnasium ausbauten; 1615 zogen
die Patres selbst in einem ehemaligen Kloster ein, das lange leer gestanden
hatte und zeitweilig im Besitz der Lutheraner gewesen war. Schließlich wurde
drei Jahre später ihre seit 1601 am Ort befindliche Ordenssiedlung in den Rang
eines Kollegs erhoben.<a name="_Ref157539946"></a><a href="#_edn2" name="_ednref2" >[2]</a> Die doppelte Promotion
im Jahre 1629 krönte den Erfolg dieser jesuitischen Bildungsoffensive.
Bezeichnenderweise war es ein Jesuiten-Pater, Dr. Johannes Bettingen, der als
Dekan der Theologischen Fakultät die Veranstaltung leitete. Die zwei neu
Promovierten vertraten jeweils den Ordens- und den Weltklerus. Neben dem
Augustinereremiten, Pater Jacobus Zeilier, disputierte auch der Priester Caspar
Heinrich Marx, um den es im Folgenden gehen wird.</p>

<p align="justify">Caspar Heinrich Marx ist bei der Erlangung seiner Doktorwürde 29 Jahre
alt. Er erhielt eine Ausbildung, die des Sohnes eines kurmainzischen
Amtsträgers würdig war. Sein Vater ließ ihn bereits mit sieben Jahren an der
Erfurter Universität einschreiben und schickte ihn darauf nach Mainz, wo er das
dortige Jesuitenkolleg besuchte und später Philosophie an der Universität Mainz
hörte. Mit 16 Jahren erhielt er die Tonsur und machte somit den ersten Schritt
auf dem Weg einer Karriere als Priester. Die Priesterweihe erhielt Marx erst
mit 25 Jahren, trat aber kurz darauf, im gleichen Jahr, in die Stiftskirche St.
Marien als Kanonikus und Kantor ein.<a name="_Ref157532496"></a><a href="#_edn3" name="_ednref3" >[3]</a></p>

<p align="justify">Unter den drei Personen, die aktiv an der Promotion im
November 1629 teilnahmen, war er der einzige in Erfurt Geborene. Der
Vorsitzende,<i> </i>Dr. Bettingen, stammte aus Trier. Der andere Kandidat
Zeilier kam aus Diedenhofen in Lothringen (heute Thionville).<a href="#_edn4" name="_ednref4" >[4]</a> Dieses Trio spiegelte
die Lage des Katholizismus in Erfurt gut wieder. Marx war Teil einer kleinen,
aber heterogenen Gruppe katholischer Kleriker und weltlicher Amtsträger, die
oft aus weit entfernten katholischen Territorien nach Erfurt gekommen waren.
Neben den Beamten des Stadtherrn, des Kurfürsten von Mainz, standen der
Stiftsklerus und die Ordensgeistlichen. 1618 gab es noch fünf Mönchs- und vier Nonnenklöster
in der Stadt. Marx gehörte zum St. Marien-Stift, dem größten der beiden Stifte,
deren Kirchen nebeneinander auf dem Domhügel stehen und über die Stadt ragen.
Doch in gewisser Hinsicht trügt die bauliche Größe. Erfurt war zu dieser Zeit
kein Bistum und zahlenmäßig waren die Katholiken hier in der Minderheit. 1620
zählten sie, die Kleriker, Beamten und Nonnen, die Männer, Frauen und Kinder,
wohl höchsten 2000 Köpfe, in einer Stadt bewohnt von etwa 17 000 Lutheranern.<a
href="#_edn5" name="_ednref5" >[5]</a></p>

<p align="justify">Um die Doktorwürde zu erlangen, disputierte Marx im
Laufe des Jahres 1629 dreimal über theologische Thesen. Alle drei Disputationen
wurden umgehend zum Druck befördert, um zu dokumentieren wie ”die theologischen
Wettstreitigkeiten und Stellungnahmen” jetzt ”mit göttlicher Hilfe” in der
”sehr alten Universität Thüringens, die in Erfurt liegt, nach einer
Unterbrechung von mehr als hundert Jahren [...] nun wieder eingeführt” worden
seien ”in ihrer vorherigen Strenge”.<a href="#_edn6" name="_ednref6" >[6]</a> 
Doch es sind nicht diese Drucke, die hier behandelt werden
sollen. Im Zentrum steht vielmehr das Tagebuch, welches „von der Zeit der
Niederlage des kaiserlichen Heeres am 17./7. September im Jahr 1631 an”<b> </b>geführt
wurde, wie sein Titel angibt.<a name="_Ref157533444"></a><a href="#_edn7" name="_ednref7" >[7]</a> Die Schlacht bei
Breitenfeld mit dem großen Sieg Gustav Adolfs führte dazu, dass die
kaiserlich-ligistische Kontrolle über Mitteldeutschland zusammenbrach. Als der
städtische Rat daraufhin einwilligen musste, eine schwedische Garnison
aufzunehmen, verschlechterten sich auch die Lebensbedingungen der städtischen
Katholiken. Marx gibt die Furcht vor einer bisher nicht vorstellbaren
Veränderung der Lage des katholischen Klerus als Grund dafür, ein Amtstagebuch
zu führen.<a name="_Ref168980519"></a><a href="#_edn8" name="_ednref8" >[8]</a>
Während die Dissertationen, verfasst im Jahr 1629, dem Jahr des kaiserlichen
Restitutionsedikts, das Wiedererstarken des Katholizismus in Erfurt vorführen
wollten, sollte das Tagebuch nachweisen, wie Marx die Rechte seines Stiftes in
einer Zeit der Prüfung standhaft verteidigte.</p>

<p align="justify">Fragt man, wie die erste schwedische Besatzungszeit zwischen 1631 und
1635 von den Katholiken erfahren wurde, so lässt sich zumindest für die
Geistlichen festhalten, dass ihre Beschimpfungen zunahmen und die Furcht, Opfer
physischer Gewalt zu werden, wuchs. Die Gefahren kamen von vielen Seiten. Den
Lutheranern wurde es jetzt ermöglicht, ihrer Abneigung gegen die „Papisten“
freien Lauf zu lassen. Als der Rat es im September 1632 unterließ, die
katholische Minderheit zu schützen, erstürmten lutherische Bürger den Domhügel
und erkämpften sich Zugang zur Marienkirche. Der lutherische Laie Hans Krafft beschrieb
in seiner Chronik dieses Ereignis mit Sympathie und kämpferischem Geist: „Wir
haben mit zwei Orgeln, Instrument Lauten, Harfen, Pauken, Pfeifen und Geigen
eine herrliche, stattliche, überaus schöne Musik gehalten. Aber es wollte den
Papisten nicht gefallen, sie wollten die Türme [für das Läuten der Glocken]
nicht eröffnen. Sie [die Lutheraner] mussten drei Türen aufbrechen, dass sie zu
den Glocken kommen konnten.”<a name="_Ref158780901"></a><a href="#_edn9" name="_ednref9" >[9]</a> Etwa ein Jahr danach
drangen lutherische Bürger erneut in die Kirche ein und griffen dort
Heiligenstatuen an.<a name="_Ref157536920"></a><a href="#_edn10" name="_ednref10" >[10]</a> Soldaten entdeckten
bereits kurz nach dem Einmarsch, dass „Pfaffen“ leichteren Opfer für Räuberei
und Einbrüche waren als lutherische Bürger.<a href="#_edn11" name="_ednref11" title="">[11]</a> Die Militärbefehlshaber
wiederum, die neben Macht auch Autorität besaßen, forderten ab dem ersten
Besatzungsmonat wie auch andertwertig üblich höhere Kriegssteuern vom Klerus
und drohten mit gewaltiger militärischer ‘Exekution’, falls ihre Kontributionen
ausbleiben sollten.<a href="#_edn12" name="_ednref12" >[12]</a>
Zudem setzte der städtische Rat den Klerus und die Klöster unter zunehmenden
Druck. Einzelne Orden waren bereits 1632 aus ihren Klöstern vertrieben und
ihnen andere Gebäude zugewiesen worden. Der Rat wies im Laufe des Jahres 1633
diejenigen Geistlichen aus der Stadt hinaus, die sich weigerten, ihm Treue zu
schwören; ”subscribiren oder migriren” forderte der Ratsbeauftragte Dr. Thiel.<a
href="#_edn13" name="_ednref13" >[13]</a>
Auf Geheiß des Rates wurde auch Marx, nach langer Verhandlung und schriftlichem
Tauziehen, seiner Stelle an der Universität enthoben. Der lutherische Theologe,
Johann Matthäus Meyfart, den Marx schon 1630 mit einer Streitschrift
herausgefordert hatte, wurde nun nach Erfurt berufen. Zeitweilig übernahm er
sogar Marx’ Stelle als Dekan der theologischen Fakultät.<a name="_Ref157252887"></a><a
href="#_edn14" name="_ednref14" > [14]</a></p>

<p align="justify">Von den erhaltenen Quellen vermittelt das von Marx geführte Amtstagebuch
wohl den besten Einblick in die Problemen, mit denen der katholische Klerus in
dieser Zeit zu kämpfen hatte. Im Folgenden wird zunächst kurz auf den Verfasser
und seine Schrift eingegangen. Danach soll besprochen werden, wie
Stadthistoriker das Amtstagebuch von Marx bislang als Dokumentation für das
Leiden der Katholiken unter schwedischer Fremdherrschaft genutzt haben.
Abschließend wird diskutiert, inwieweit das Amtstagebuch auch als Selbstzeugnis
gelesen und verstanden werden kann.</p>

<h5>1. Bemerkungen zum Amtstagebuch.</h5>
<p align="justify">Diese Quelle ist kein privates Tagebuch im modernen Sinne; sie wurde zu
amtlichen Zwecken verfasst. Gegen Ende des Jahres 1631 beginnt Marx, Eingriffe
und Übergriffe der lutherischen Machthaber zu dokumentieren. Er greift dazu auf
einen vorher weitgehend unbeschriebenen Band zurück, dessen erste sieben Seiten
mit zwei Urkunden eröffnet werden.<a href="#_edn15" name="_ednref15" >[15]</a>
Die ersten Einträge sind wahrscheinlich zur Jahreswende 1631/1632 hin
geschrieben. Damals blickte Marx besorgt auf die 
„Acta des 1631 iahrs“ zurück, als Überfälle zur
Tagesordnung gehörten. Soldaten störten wiederholt absichtlich den Gottesdienst
und „wir Geistlichen sassen in forcht, <s>und</s> Zitter, undt pressuren
[Bedrückungen zu Hause und auf den Strassen], in deme auch keiner [ungeschmäht]
fast uber die Gassen gehen derffen.“<a href="#_edn16" name="_ednref16" >[16]</a>
Die kommenden Jahre unterschieden sich jedoch von diesen ersten chaotischen
Monaten der Besatzung. Von 1632 bis 1635 sollte die Bedrohung weniger von
einzelnen Soldaten auf der Suche nach Beute ausgehen. Nun waren es vielmehr die
unterschiedlichen lutherischen Obrigkeiten, die nach Kontributionen, Gütern und
Gehorsam verlangten.</p>

<p align="justify">In diesen vier Jahren hat Marx reichlich Grund, sein
Diarium fortzusetzen. Seine häufigen Einträge geben Zeugnis davon, wie die
aktuellen (Heraus)forderungen sich von Woche zu Woche und von Monat zu Monat
wandelten. Wöchentlich, täglich, ja manchmal stündlich trägt er seine
Bemerkungen ein. Er schreibt auf die Schnelle; beim ersten Blättern fallen vor
allem die vielen ausgestrichenen Passagen und Zusätze am Rande auf. Neben
abgeschickten, empfangenen und entworfenen Briefen enthält das Amtstagebuch
auch viele Protokolle aus internen Beratungen des Klerus. Marx hält Treffen mit
den Kollegen aus seinem Stift und den restlichen katholischen Gemeinden und
Klöstern fest. Die Geistlichen debattierten, wie sie auf die jeweils neuesten
Forderungen seitens der Besatzungsmächte oder des Rates reagieren sollten, und
sie waren hierbei keineswegs immer einer Meinung. Marx zeigt sich hier durchaus
als ein parteilicher Protokollant, der die Debatten meist in aller Kürze
wiedergibt. Er verteidigt Beschlüsse, mit denen er sympathisiert, gegen die
interne Kritik seitens anderer katholischer Kleriker und Beamten.</p>

<p align="justify">Das Amtstagebuch gleicht in gewisser Hinsicht einer
doppelten Buchführung. Auch andere Kollegen führten Protokolle dieser internen
Treffen für das Stiftsarchiv.<a href="#_edn17" name="_ednref17" >[17]</a>
Der Wert eines zweiten, separaten Protokolls wird Marx ab der ersten Woche der
Besatzung klar gewesen sein. Denn sehr bald begannen die Soldaten, die
Stiftshäuser nahe bei ihrem Lagerfeuer zu plündern und die dort aufbewahrten
Archivalien zu zerstreuen. Danach inspizierten schwedische Deputierte die
Schränke des Marienstifts; später entnahmen sie auch der Mainzer Amtsstube
wertvolle Archivalien. Ein Jahr darauf, im Dezember 1632, fingen Ratsdiener
schließlich an, eigene Kloster- und Stiftsinventare zu erstellen und
Archivalien in das Rathaus zu überführen.<a href="#_edn18" name="_ednref18" title="">[18]</a> In dieser unsicheren
Situation diente das Tagebuch seinem Schreiber auch als eine Art privates
Archiv. Es sollte ihm und seinen späteren Lesern wichtige Daten dauerhaft
sichern, und ihnen somit helfen, die von ihnen als rechtswidrig erfahrenen
Eingriffe später wieder rückgängig zu machen und Restitution zu erlangen.</p>

<p align="justify">Die Tagebucheinträge enden im Oktober 1635. Wenige
Monate zuvor, im Juli, ist die Stadt dem Prager Frieden beigetreten. Eine
zentrale Friedensbedingung war die Rückgabe aller Güter, die nach 1627
beschlagnahmt worden waren. Marx fängt deshalb in den auf den Prager Frieden
folgenden Monaten an, seine Notizen zu benutzen, um Forderungen geltend zu
machen.<a name="_Ref159646807"></a><a href="#_edn19" name="_ednref19" >[19]</a>
Sein letzter Eintrag im Tagebuch gibt ein Schreiben an den Mainzer Abgeordneten
in Erfurt Johann Christoph von Harstall<i> </i>wieder. In ihm ersucht Marx
darum, ihn wieder seine Stelle als Dekan der Theologischen Fakultät der
Erfurter Universität zurück zu übertragen, die ihm im Juli 1633 aberkannt
worden war. Dank seiner Notizen kann Marx genau belegen, wann und auf wessen
Befehl ihm welche Insignien damals abgenommen worden waren. Er verspricht,
weiterhin genauestens, von „dag zue tag genugsamb demonstriren”<i> </i>zu
können, wie kläglich der damalige lutherische Rektor Justus Heckel es
unterließ, ihn, Marx, als Kollegen und Mitglied der Universität zu schützen.<a
name="_Ref157532685"></a><a href="#_edn20" name="_ednref20" >[20]</a>
Marx durfte die ersten Erfolge dieser Bemühung noch erleben. Ein Katholik aus
seinem Stift, Johannes Lambert Winter<i>, </i>wurde
wieder Dekan der theologischen Fakultät.<a name="_Ref157252911"></a><a
href="#_edn21" name="_ednref21" > [21]</a> Doch am
Ende des Jahres, gerade zu dem Zeitpunkt als seine Notizen begannen, ihren
Nutzen zu zeigen, starb Marx an der Pest. Dieser frühe Tod, am 18.12.1635,
beraubte ihn der Möglichkeit, sein Tagebuch weiterhin selbst für die erhoffte
Restitution der Universität zu benutzen; sie sollte bis 1649 lutherisch
bleiben.</p>

<p align="justify">Die Frage, ob und wie die Mainzer Beamten und
Stiftsgeistlichen das Tagebuch nach 1635 verwendeten, ist die wohl dringlichste
quellenkritische Aufgabe, die nach der Edition der Quelle weiterhin bestehen
bleibt. Spätere Auszüge aus dem Text, die sich im Archiv des Erfurter
Marienstifts befinden, belegen, dass Stiftsgeistliche das Diarium lasen – wahrscheinlich
um ihre Ansprüche bei der Restitution durchzusetzen.<a href="#_edn22" name="_ednref22" >[22]</a>
Es bleibt offen, ob die kritischen Notizen zum Verhalten einzelner katholischer
Kleriker und Beamter auch Konsequenzen für diese Personen selbst hatten? Zu
untersuchen wäre weiterhin auch, ob die von Marx angegebenen Beilagen (meist
Abschriften der Korrespondenz) noch erhalten sind und wo sie sich
gegebenenfalls befinden. Archivrecherchen könnten klären, ob fehlende Berichte,
die Marx in das Tagebuch einfügen wollte, heute anderswo überliefert sind -
oder ob er sie zwar plante, aber nie schrieb.<a href="#_edn23" name="_ednref23" title="">[23]</a></p>

<h5>2. Die bisherige Beschäftigung mit dem Autor und seinem Amtstagebuch.</h5>

<p align="justify">Caspar Heinrich Marx ist in der Erfurter Stadtgeschichte keineswegs
unbekannt. Seine erste Biografie wurde kurz nach seinem Tod vom damaligen
Rektor der Universität, Henning Rennemann<i>, </i>veröffentlicht, in Form eines
(in doppelter Hinsicht) einseitigen Nekrologs.<a href="#_edn24" name="_ednref24" title="">[24]</a>
Es war üblich, dass der jeweils amtsinhabende Rektor das Leben eines
verstorbenen Universitätsangehörigens würdigte. Doch dieser Nekrolog war mehr
als eine amtliche Pflichtübung; er glich einem politischen ‘statement’. Marx
wird hier als einer der wenigen ‘guten’ Katholiken beschrieben, welche in den
zurückliegenden Jahren standhaft auf ihrem Posten verbliebent. Er vertrat öffentlich
sein Amt, während andere Geistliche sich versteckten. Die Mehrheit seiner
Kollegen seien aus der Stadt geflüchtet, um den gewalttätigen Soldaten zu
entgehen<i>.</i><a href="#_edn25" name="_ednref25" >[25]</a>
Rennemann schreibt nur positiv von dem verstorbenen Marx, wie es zum Genre
gehörte: „de mortuis nihil nisi bene“ lautete die Devise. Vergessen war die
Fehde der vergangenen Monaten zwischen Marx und dem lutherischen Professor
Nikolaus Zapf. Deren gegenseitige Schmähungen und ihre „plakativen“
Behauptungen eigener Rechte in Oktober 1635 wurden stillschweigend übergangen.<a
href="#_edn26" name="_ednref26" >[26]</a></p>

<p align="justify">Wenn Rennemann den Verstorbenen als umgänglich lobte,
so geschah das auch in eigenem Interesse.<a href="#_edn27" name="_ednref27" title="">[27]</a>
Der lutherische Jura-Professor und leitendes Ratsmitglied war zu dieser Zeit an
den Bemühungen beteiligt, die 1633 errichteten lutherisch-theologischen
Professuren zu erhalten. Zu diesem Zweck suchte der Rat die im Prager Frieden
vorgeschriebene Rückgabe der von den Lutheranern bei der Wiedergründung der
Universität angeeigneten Fakultätsrechte zu umgehen.<a href="#_edn28" name="_ednref28" >[28]</a>
Wochen vor Marx’ plötzlichem Tod hatte der Rat eine Apologie verfasst, die auch
kurz auf Marx biografisch einging. Auch damals hob man von seiten des Rates
hervor, wie freundlich Marx mit vielen seiner lutherischen Kollegen umging. Zu
seinen Lebzeiten wehrte sich Marx gegen solches tendenzielle und pauschale Lob.<a
href="#_edn29" name="_ednref29" >[29]</a>
Dessen mögliche Implikationen waren ihm klar: Marx habe auf freundlichen Fuß
mit den Professoren augsburgischer Konfession gestanden und habe damit de facto
die Änderungen seit 1632 toleriert und gut geheißen. Marx selbst hingegen
unterstrich, wie freundlich seine Verbindungen zu den „alten“ lutherischen
Professoren waren, die bereits vor 1632 an der Erfurter Universität lehrten,
und wie sie sich vom feindlichen Verhältnis zu den neu berufenen und
konfessions-kontroversen Theologen, wie Georg Großhain und Nikolaus Zapf,
unterschieden.<a href="#_edn30" name="_ednref30" >[30]</a></p>

<p align="justify">Spätere Biografen haben diesem eigennützigen Lob von lutherischer Seite
einige Details hinzugefügt. Just Christoph Motschmann nahm 1730 Marx in seine
lokale Gelehrtengalerie auf. Dort erwähnte Motschmann auch eine ihn
diffamierende Mord-Anklage, deren Unhaltbarkeit Marx selbst des öfteren
hervorgehoben hatte<i>.</i><a name="_Ref156973169"></a><a href="#_edn31" name="_ednref31" >[31]</a><i> </i>Anhand
der hier editierten Schriften von Marx beschrieb Otto Bock 1907 eine Episode
der Universitätsgeschichte.<a name="_Ref164140497"></a><a href="#_edn32" name="_ednref32" >[32]</a>
Schließlich gab Erich Kleineidam 1980 eine Übersicht über Schulbildung und
akademischen Werdegang des Schreibers.<a href="#_edn33" name="_ednref33" title="">[33]</a></p>

<p align="justify">Trotz der Aufmerksamkeit, die Marx in Kurzbiografien zuteil wurde, war
der katholische Priester und Kirchenhistoriker Franz Schauerte bis vor Kurzem
der Einzige, der Marx’ Amtstagebuch ausführlich verwendete.<a href="#_edn34" name="_ednref34" >[34]</a>
Seine Abhandlung zu ”Gustav Adolf und die Katholiken in Erfurt” erschien 1887
bei der katholischen „Görres-Gesellschaft zur Pflege der Wissenschaft im
katholischen Deutschland“ als Beitrag zu einem lange andauernden historischen
Streit um die Bewertung der historischen Rolle der habsburgischen Kaiser und
des schwedischen Königs Gustav Adolf im Dreißigjährigen Krieg.<a href="#_edn35" name="_ednref35" >[35]</a> Im 19. Jahrhundert
hatte dieser Historikerstreit höchst aktuelle Bezüge. Der politische Kampf um
eine klein- oder eine großdeutschen Lösung wurde gewissermaßen auch auf den
Schlachtfeldern des Dreißigjährigen Krieges virtuell in der historischer
Retrospektive ausgefochten und in zahlreichen Theaterstücken, historischen
Romanen und akademischen Studien verarbeitet. Nach 1871 änderte der Streit
seinen Charakter. Im Rahmen des sogenannten Kulturkampfs ging es jetzt um den
Platz der deutschen Katholiken im neugegründeten wilhelminischen Kaiserreich.
Schauertes kämpferischen Ton versteht man besser, wenn man ihm Werke gegenüber
stellt, die, voll von preußisch-protestantischem Patriotismus, den schwedischen
‘Löwen aus Mitternacht’ feiern.<i> </i>So geben etwa die Schriften des
Thüringer Theologen Ottomar Lorenz in typischer Weise wieder, wie der ‘Retter
des evangelischen Glaubens’ damals die Lutheraner in Deutschland vom
katholischen Joch befreit habe. Der sicherlich dramatischste Ausdruck dieser
Gesinnung ist sein „Volksstück“ über „Gustav Adolf in Erfurt“. Herausgegeben
wurde es 1889 von dem kurz zuvor in Erfurt gegründeten „Evangelischen Bund zur
Wahrung Deutsch-Protestantischer Interessen”.<a name="_Ref156635331"></a><a
href="#_edn36" name="_ednref36" >[36]</a></p>

<p align="justify">Um einen solchen Gustav-Adolf-Kult zu revidieren, will
Schauerte ”die Schicksale der Erfurter Katholiken in der Schwedenzeit kurz
erzählen”. Er widmet sich einzelnen Ereignissen. Eingriffe, Überfälle und
maßlose Forderungen reiht er in einer „Kette der
Leiden“ aneinander.<a href="#_edn37" name="_ednref37" >[37]</a>
Zu diesem Zweck wertete er Stiftsprotokolle aus Erfurt und Archivalien aus
Wernigerode aus; ergänzend zog er vereinzelt lutherische Chroniken und Ratsprotokolle
hinzu. Diese Quellen hat er zuverlässig zusammengefasst, wobei er durchgängig
die katholischen Klageschriften gegenüber den lutherischen Rechtfertigungen
bevorzugt. Der Leser von Marx’ Tagebuch kommt also nicht um Schauertes Schrift
herum, wenn er sich einen Überblick über die wichtigsten Ereignisse in der Zeit
zwischen 1631 und 1635 verschaffen will. Da Schauertes Studie noch heute von
beträchtlichem Nutzen ist, lohnt sich eine kritische Auseinandersetzung mit
ihr. Im Folgenden sollen drei ihrer Schwächen aufgezeigt werden: Erstens stellt
Schauerte die Katholiken und die Lutheraner zu sehr als zwei homogene Blöcke
dar. Zweitens dramatisiert er die Notlage der Katholiken. Und drittens hebt er
die Konflikte unter den Katholiken zu wenig hervor.</p>

<p align="justify">Zuallererst jedoch irritieren die mangelhaften
Angaben. Für einzelne Zitate werden entweder keine Quellen angegeben oder die
Archivreferenzen sind ungenau und mittlerweile veraltet. Die Überprüfbarkeit
der Darstellung wird dadurch erschwert. Doch das eigentliche Problem bei den
Quellenangaben entsteht wohl dadurch, dass der Autor versucht, seinem Motto
treu zu bleiben: akademisch zu streiten ”[m]it vereinten Kräften für Glaube und
Wahrheit!”.<a name="_Ref157259791"></a><a href="#_edn38" name="_ednref38" title="">[38]</a> Schauerte betont, dass
auch die damaligen katholischen Geistlichen vereint als ”ein[e] einmüthige
Brüderschaar [...] in jenen drohenden Gefahren fest zusammen” standen. Wenn
Schauerte die Aussage eines Erfurter Katholiken zitiert, bedeutete es für ihn
folglich nicht viel, wer da genau spricht. Marx taucht so wiederholt bei
Schauerte lediglich als ”der Chronist” auf, ohne namentlich zitiert zu werden.<a
href="#_edn39" name="_ednref39" >[39]</a> Das Problem
dieses einseitig harmonisierenden Blickwinkels wird dem Leser dann klar, wenn
er selbst bei Schauerte (und verstärkt in Marx’ Amtstagebuch selbst) Hinweise
darauf findet, dass die Katholiken durchaus uneinig darüber waren, wie sie sich
gegenüber den Besatzungsmächten verhalten sollten. Diese Meinungsunterschiede
werden weiter unten thematisiert.</p>

<p align="justify">Schauerte schildert nicht nur die katholischen Helden
zu homogen; auch die lutherischen Gegner könnten besser von einander
unterschieden werden. Schauerte bemüht sich hauptsächlich darum, König Gustav
Adolf für das Leiden der Erfurter Katholiken mitverantwortlich zu machen. Es
waren deshalb für ihn nicht nur die örtlichen Handlanger und Alliierten, welche
„die Dornenkrone dem Klerus noch tiefer in’s
Haupt“ drückten, vielmehr war die Verfolgung von höchster Stelle
gewollt.<a name="_Ref174247959"></a><a href="#_edn40" name="_ednref40" >[40]</a>
Um Marx’ Aufzeichnungen zu verstehen, ist es jedoch notwendig, die folgenden
drei getrennten Gewalten klar von einander zu unterscheiden.</p>

<p align="justify">Die schwedische Krone bestimmte seit September 1631 die
Situation des Erfurter Klerus. An ihrer Spitze standen König Gustav Adolf und,
nach dessen Tod, der Reichskanzler Axel Oxenstierna. Sie beließen stets ihren
Repräsentanten in der Stadt. Der Resident Dr. Jakob von Steinberg (und nach ihm
Alexander Erskein) sollte vor allem auch ein wachsames Auge auf den regionalen
Verbündeten, Herzog Wilhelm IV. von Weimar, werfen, der zweiten mächtigen
Instanz in der Region. Gustav Adolf verbündete sich im Laufe seines Feldzugs
1631-1632 mit vielen lutherischen Fürsten, nicht zuletzt um Kosten bei der
Kriegsführung einzusparen.<a href="#_edn41" name="_ednref41" >[41]</a>
Seine Konföderierten wiederum nahmen oft das Risiko der kaiserlichen Ächtung im
Kauf, weil sie selbst territoriale Gebietsgewinne erhofften. So plante auch
Wilhelm IV. von Weimar in erster Linie, das in nordwestlicher Richtung gelegene
katholische Eichsfeld seinem Herrschaftsbereich einzugliedern; aber auch die
Schutzherrschaft in der benachbarten Stadt Erfurt erhoffte er zu gewinnen. Wann
immer er nur konnte, wälzte er selbstverständlich, wie jeder andere Kriegsherr,
die Kosten der Kriegsführung auf die Stadt ab. Der „Stadt halter [...] ist
worden zum Stadt Verwüster“<b> </b>hielt ein empörter, steuermüder
Chronikschreiber aus Erfurt fest.<a href="#_edn42" name="_ednref42" >[42]</a>
Der dritte Entscheidungsträger war der städtische Rat. Nach der Aufnahme einer
schwedischen Garnison, bemühten sich die federführenden Oligarchen im Rat
mithilfe der schwedischen Allianz darum, ihre Unabhängigkeit gegenüber dem
nominellen Stadtherrn, d.h. dem Kurfürsten und Erzbischof von Mainz zu stärken.
Teil dieser Bemühungen war es, die Universität samt der katholischen Klöster
und Pfarrkirchen unter die eigene Kontrolle zu bringen. Sie versuchten mit
Erfolg, Gustav Adolf und Axel Oxenstierna für solche Pläne zu gewinnen. Die
Forderungen des Erfurter Rates stellten also die weitreichendere Drohung für
die Katholiken dar. Der schwedische Resident Erskein und der Weimarer
Kriegszahlmeister Evander forderten in erster Linie lediglich Geld.<a
href="#_edn43" name="_ednref43" >[43]</a></p>

<p align="justify">Das zweite gewichtige Problem ist,
dass Schauerte konsequent die Notlage der katholischen Geistlichen übertreibt.
”[U]nter den katholischen Geistlichen Erfurt’s [herrschte] Jahre lang die
äußerste Noth”<a href="#_edn44" name="_ednref44" >[44]</a>.
Dieser Superlativ ist erstens durch den spezifischen Charakter der von ihm
benutzten Quellen bedingt. Schauerte stützt seine Studie vor allem auf
Klageschriften. Aus ihnen ergibt sich eine lückenlose ”Kette der Leiden” für
die Katholiken; ”war die eine Nothlage vorüber, so kam die andere.”<a
href="#_edn45" name="_ednref45" >[45]</a>
Zweitens geht es aber dem Autor neben wissenschaftlicher Glaubwürdigkeit auch um den Glauben
selbst. So kommt es zu hagiographischen Formulierungen von dem ”schweren
Kreuz der Verfolgung” worunter die Katholiken „seufzten”. Der triumphale Einzug
Gustav Adolfs wird so zum “Leichenbegängnis der katholischen Kirche in Erfurt.”<a
href="#_edn46" name="_ednref46" >[46]</a></p>

<p align="justify">Diese drastische Deutung ist nur bedingt tragfähig. Das
Eindringen in die Klöster und katholischen Kirchen hatte seine Grenzen. Als der
sitzende Rat im November 1632<i> </i>erst Vorsteher in den Klöstern einsetzte<i>
</i>und dann Kirchenschlüssel anzufordern begann, führte er eine schon länger
bestehende Politik fort. Denn schon seit der Mitte des 16. Jahrhunderts hatte
der Rat mehrfach versucht, bestehende Klöster und Kirchen für den lutherischen
Glauben zu gewinnen; zumeist griff er dabei erst dann ein, wenn ein Priester
oder das letzte Ordensmitglied eines Konvents starben.<a name="_Ref164243886"></a><a
href="#_edn47" name="_ednref47" >[47]</a> Marx und
seine geistlichen Kollegen sahen, wie der Rat in der neuen Situation versuchte,
lutherische Pfarrer in den umliegenden katholischen Dörfern einzusetzen. Sie
befürchteten durchaus zu Recht, dass der Rat mit diesen Maßnahmen dem
katholischen Glauben in Erfurt schrittweise auf lange Sicht ein Ende bereiten
wollte; Marx übertrieb somit nicht, als er in einem Rückblick Ende 1635 behauptete,
dass der Rat ihnen „gern den garauß gemacht hette“.<a href="#_edn48" name="_ednref48" >[48]</a> Da der Dreißigjährige
Krieg jedoch oft allgemein als eine Zeit der Brandschatzungen, Vergewaltigungen
und Massaker geschildert wird, führen Schauertes entsprechend dramatische
Phrasen leicht in die Irre. Der Rat ging gegen den Klerus ”in seinem
Zerstörungswerke” nicht vorrangig mit physischer Gewalt vor. Nachdem die
schwedische Krone ihm Rechte an den katholischen Kirchen und Klöster übereignet
hatte, versuchte der Rat vielmehr, durch kontrollierte Machtanwendung zu
erzwingen, dass der Klerus seine Herrschaft als legitim anerkannte.<a
href="#_edn49" name="_ednref49" >[49]</a> Dieser
abgestufte Druck ließ jeweils noch viel Raum für Verhandlungen übrig. Als der
Rat durch Universitätsbeamte die Dekanatsinsignien von Marx forderte, konnte
Marx ihnen entgegnen, dass er niemals freiwillig seine Fakultätskiste abgeben
wolle, sondern dies nur unter Anwendung von Gewalt geschehen lassen müsse.
Dieser Hinweis war durchaus wirksam, denn Marx wusste, dass Gewalt für den Rat
nur die letzte Option war. Der Rat versuchte eher, die katholischen
Entscheidungsträger zu einem ‘freiwilligen’, rechtsgültigen Einlenken zu
zwingen.<a href="#_edn50" name="_ednref50" >[50]</a></p>

<p align="justify">Der Stiftsklerus und die
unterschiedlichen Orden reagierten auf den steigenden Druck verschieden. Manche
Geistliche flüchteten schon vor oder während der schwedischen Besatzung.<a
href="#_edn51" name="_ednref51" >[51]</a>
Andere blieben in der Stadt und lehnten es kategorisch ab, neben dem König auch
dem städtischen Rat Treue und Unterwerfung zu schwören. Dafür wurden sie Ende
Dezember 1633<i> </i>wie Kriminelle öffentlich gedemütigt und aus der Stadt
verwiesen. In den Augen der Verwiesenen konnten die Kompromisse der
Zurückgebliebenen, unter ihnen Caspar Heinrich Marx, leicht als Schwäche
ausgelegt werden. Der damit verbundene Streit unter den katholischen
Entscheidungsträgern wird von Schauerte durchgängig untertrieben. Die vereinte,
”einmüthige Brüderschaar” der katholischen Geistlichen und Laien fanden, so
Schauerte, ”in dem festen Zusammenhalt mit einander [...] Trost und Kraft, um
den schweren Drangsalen nicht völlig zu unterliegen.”<a href="#_edn52" name="_ednref52" >[52]</a> Diese dritte Schwäche
seiner Darstellung ist im Hinblick auf das Verständnis des vorliegenden
Amtstagebuches vielleicht die größte. Schauertes eigene Befunde sprechen gegen
sein pauschales Lob. Als Marx durch zähe Verhandlung und Kompromisse die
Stiftsgeistlichen vor der Ausweisung bewahrte, wurde sein Handeln von einem
Mainzer Beamten, Johannes Dresanus, angegriffen. Die Stiftsgeistlichen sahen es
daraufhin als notwendig an, eine Apologie zu verfassen.<a href="#_edn53" name="_ednref53" >[53]</a></p>

<p align="justify">Diese Konfrontation war keineswegs einzigartig. Die
‘kleineren Übel’, welche die Zurückgebliebenen wie Marx wiederholt akzeptieren
mussten, um überhaupt bleiben zu können und um so ‘größeres Übel’ zu vermeiden,
gaben genügend Anlass zum Streit.<a href="#_edn54" name="_ednref54" >[54]</a>
Ein gutes Beispiel ist der problematische Beschluss vom Februar 1632, das Haus
eines verstorbenen Priesters an den Weimarer Gesandten, Dr. Daniel Burchardt,
zu verkaufen. Marx hebt dessen günstige Folgen hervor. Wiederholt legte
Burchardt ein gutes Wort ein, wenn das Stift ihn darum bat. Erst Burchardt
vermochte, nachdem ihm das Haus auf seinen Wunsch hin verkauft worden war,
einen wirklichen Schutz zu gewährleisten. Somit half er dem ”Clerus et populus
Catholicus der bishero der Religion undt Exercitii [Religionsausübung] halber
getragener furcht undt gelittener Molestion [Belästigung] in den kirchen einen
gewunschten drost” zu erlangen. Dass nun dieser „sonderbahrer gueter freundt
und Patron“ des Klerus zuvor, kurz nach dem Einzug der Schweden, der Plünderung<i>
</i>der städtischen Klöster vorgestanden hatte,<i> das </i>lässt Marx hingegen
unerwähnt.<a href="#_edn55" name="_ednref55" >[55]</a>
Das Amtstagebuch diente somit auch Marx zur eigenen Rechtfertigung.</p>

<p align="justify">Marx wandte sich in seiner Rechtfertigungsschrift auch
gegen interne Gegner. Kritisiert wird dort vor allem ein weiterer katholischer
Doktor des Jahres 1629, der Mainzer Schultheiß und Doktor beider Rechte,
Johannes Dresanus. Als Vertreter des Mainzer Kurfürsten stand Dresanus qua Amt
in einer gewissen Spannung zu den Stiftsgeistlichen, die oft aus Sachsen
stammten oder aber aus dem städtischen katholischen Patriziat gewählt wurden.<a
name="_Ref162783993"></a><a href="#_edn56" name="_ednref56" >[56]</a>
Marx nutzte denn auch jede Gelegenheit, um Dresanus anzuschwärzen. Blättert man
zum ersten Mal in dem hier edierten Manuskript, dann sind es die Rand-Notizen
”NB. Dresanus”, die als Erstes auffallen.<a href="#_edn57" name="_ednref57" title="">[57]</a>
Sie verweisen auf Episoden, in denen sich der Mainzer Schultheiß, laut Marx,
eigenartig oder sogar verräterisch verhielt.</p>

<p align="justify">Übrigens war Marx weder der erste noch der letzte
Erfurter Geistliche, der sich anhand solcher Aufzeichnungen vor Kritik
schützte. Das Amtstagebuch des Sieglers Dietrich Buhemeiger <b>(</b>gest. 1589<b>)</b>
entstand aus einem ähnlichen Spannungsverhältnis mit dem Mainzer Weihbischof
heraus.<a href="#_edn58" name="_ednref58" >[58]</a>
Und kurz nach Marx’ Tod schrieb der Prior des Kartäuserklosters, Johannes
Arnoldi, zum zweiten Mal in seinem Leben die Annalen seines Klosters. Auch
Arnoldi war in Erfurt geblieben. Auch er sah sich gezwungen, Kompromisse
einzugehen. Nach dem Ende der ersten schwedischen Besatzung 1635 nahm er sich
daher vor, sein Handeln durch ein „Diarium“ zu rechtfertigen, „eine kurze und
fast tagebuchartige Beschreibung von dem, was vor und nach dem Ankunft des
[schwedischen] Königs bei uns geschah.“<a name="_Ref156962915"></a><a
href="#_edn59" name="_ednref59" >[59]</a></p>

<h5>3. Inwieweit kann das Amstagebuch als Selbstzeugnis gelesen werden?</h5>

<p align="justify">Wer dieses Amtstagebuch als ein ‘Selbstzeugnis’ analysieren möchte,
sollte sich darüber im Klaren sein, dass Marx den von ihm ins Auge gefassten
kurmainzischen Lesern und Amtsträgern nur selten Einblicke in sein Innen- und
Privatleben gewähren wollte. Er stellt sich ihnen als ein zäher, bedächtiger
Verhandlungspartner<i> </i>vor, als ein Verteidiger des rechten Glaubens und
der kirchlichen Rechte. Der Leser sucht aber auf dem Titelblatt vergebens nach
dem Namen des Verfassers; Marx ist ein zurückhaltender Autor. Fast beiläufig
präsentiert er sich in einer Randnotiz auf Seite 8 verso. Dort lässt Marx den
Leser fragen: „Tu quis es?“ (Wer bist du?) und antwortet mit Hinweis auf einen
Eintrag zum 1. Januar 1632, wo er von sich selbst als „Autor dieses Tagebuchs“
schreibt.<a href="#_edn60" name="_ednref60" >[60]</a></p>

<p align="justify">Seine übrigen, auf die eigenen Person und auf sein
Selbst bezogenen<b> </b>Einträge sind ähnlich sachlich und zurückhaltend. Im
Unterschied zum lutherischen Blaufärber Hans Krafft schreibt er kaum von der
eigenen Familie.<a href="#_edn61" name="_ednref61" >[61]</a>
Nur einmal erwähnt er, wie räuberischen Soldaten der schwedischen Armee, kurz
nach dem Einmarsch im September 1631, in seinem Haus auf dem Petersberg
einbrachen, den Hausrat zerschmetterten, und seine Mutter und Schwester
hinausjagten.<a href="#_edn62" name="_ednref62" >[62]</a>
Zwei Tage zuvor hatte Marx selbst aus diesem „Haus Zum Bunten Schild” fliehen
müssen.<a href="#_edn63" name="_ednref63" >[63]</a>
Ansonsten klagt er wenig über das eigene erlittene Unrecht. Die infame Beschuldigung, er habe
1632 einen Universitätspedell vergiftet und ermordet, erwähnt er eher beiläufig
und indirekt.<a href="#_edn64" name="_ednref64" >[64]</a>
Nur selten lässt er sich zu Klagen mitreißen. „O Herr Gott, du siehst, in
wievielen Nöten wir festgesetzt sind!” ruft er einmal im Buch aus, auf Latein.<a
href="#_edn65" name="_ednref65" >[65]</a>
Mit „O Sendung, o Berufung“ schließt er einen
niederwerfenden Bericht über die Einsetzung eines lutherischen Pfarrers in der
bis dahin katholischen Erfurter Landgemeinde Hochheim ab.<a href="#_edn66" name="_ednref66" >[66]</a>
Etwas ausführlicher berichtet Marx an einer anderen Stelle, wie er vor
dem schwierigen Beschluss, dem Rat den Treueid zu leisten, selbst beichtet und
betet. Diese offenherzige Niederschrift sollte aber der „posteritas“, der
Nachwelt, als Beleg seiner Aufrichtigkeit dienen, sie ist Teil einer “Admonitio“,
Ermahnung, in der sich Marx mit Kritikern wie Dresanus auseinandersetzt.<a
href="#_edn67" name="_ednref67" >[67]</a>
Die andere zeitgenössische narrative Rechtfertigungsschrift eines Erfurter
Klerikers, die Chronik des Kartäuser-Priors Johannes Arnoldi, enthält deutlich
mehr an autobiografischen Notizen als dieses Amtstagebuch.<a
name="_Ref156962831"></a><a href="#_edn68" name="_ednref68" >[68]</a></p>

<p align="justify">Auch in seinem „Ohnvorgreifliche[n] Bedencken, die
Theologische Facultät betreffendt“, das Marx wenige Wochen vor seinem Tod
verfasste,<a href="#_edn69" name="_ednref69" >[69]</a>
zeigt er sich erneut als Amtsperson, und zwar weniger als Stiftsgeistliche,
sondern vielmehr als ein Dekan. Bedächtig beschreibt er hier erneut anhand
seines Tagebuches die lutherischen Ein- und Angriffe auf die
katholisch-theologische Fakultät und ihn selbst als deren Dekan; zäh zählt er
noch einmal auf, wie sein „Jus“ und sein „Ehr“ verletzt worden seien.<a
href="#_edn70" name="_ednref70" >[70]</a>
Er bemüht sich wieder „ohne die Schande der Selbstverherrlichung“ sein eigenes
Handeln zu rechtfertigen, und betont erneut wie treu er seine Eide eingehalten
habe.<a href="#_edn71" name="_ednref71" >[71]</a>
Doch manches liest sich anders und persönlicher als im Tagebuch. Wenn er die
Argumente des Rates widerlegt, dann erlaubt er sich neben der uns bisher
bekannten Sachlichkeit auch Ironie. Und als es darum geht, wie der Rektor der
Universität Justus Heckel ihn im Stich lässt, wird Marx persönlicher und
bissiger. Der „alte Magnificus“ habe zu seiner Entschuldigung bloß zaghafte und
furchtsame Worte fallen gelassen;<a href="#_edn72" name="_ednref72" >[72]</a>
er bemühte stets die Floskel („formalia“): „Herr Doctor, ihr sehet wie es
gehet, ich kann nicht[s machen]“.<a href="#_edn73" name="_ednref73" >[73]</a></p>

<p align="justify">In seinem Tagebuch zeigt sich Marx zurückhaltender und
unpersönlicher. Er schreibt kontrollierter als manche seiner anderen
Zeitgenossen. Der Ratsnotar Hermann Taute, zum Beispiel, wurde wenige Jahre
später vom Rat damit beauftragt, wichtige Kriegsereignisse und
Rechtsstreitigkeiten schriftlich festzuhalten. Taute wich jedoch oft von dem
ihm vorgegebenen Thema ab und hielt Prodigien und Wunderzeichen fest.<a
href="#_edn74" name="_ednref74" >[74]</a>
Marx hingegen erwähnt nur einmal, wie Hagelkörner so groß wie Taubeneier
fallen, „mit underschiedenen figuren et imaginibus”.<a href="#_edn75" name="_ednref75" >[75]</a>
Antikatholische Wunderberichte führt er nur kurz mit deutlich skeptischer
Distanz an.<a name="_Ref163471548"></a><a href="#_edn76" name="_ednref76" title="">[76]</a>
Ihm lagen derartige Exkurse fern; unter „wunderbare acta“ verstand er vielmehr
die bedenklichen Rechtsverletzungen der Lutheraner.<a href="#_edn77" name="_ednref77" >[77]</a>
Doch an einigen Stellen weicht er von dieser Relevanz-Gebundenheit ab: Berichte
von Schlachten und Belagerungen, die eine Wende des Kriegsglückes verhießen,
interessierten ihn offensichtlich. Er erwähnt etwa, wie Regensburg erst im
November 1633 von den schwedischen Truppen eingenommen wurde und vermerkt dann
ferner im Juli 1634 dass die Kaiserlichen die Reichsstadt wiedererobert hatten.<a
href="#_edn78" name="_ednref78" >[78]</a></p>

<p align="justify">Sein Tagebuch zeugt überdies auch von
seinem karitativen Engagement. Nicht nur in seiner einzigen gedruckten
Predigt aus dem Jahre 1632 forderte Marx Armenhilfe von seinen
Glaubensgenossen.<a href="#_edn79" name="_ednref79" >[79]</a>
Als im Winter 1634/1635 Tausende von Zivilisten vor den vorrückenden
kaiserlichen Truppen und wegen Hungersnot aus Franken nach Erfurt flüchteten,
hielt er deren kümmerliche Lebensbedingungen explizit im Diarium fest. 
Die „viel[en] arme[n] leut[en]“ wohnten vor den Toren und auf den 
Straßen; sie suchten Zuflucht „in underschidene zerfallene heuser undt keller,
undt wo sie sonsten unter dach nur ein wenig kommen konnen“ haben sie sich
hingelegt. Viele lagen auch „auf der blossen gassen“.<a href="#_edn80" name="_ednref80" >[80]</a>
Die hauptsächlich lutherischen Flüchtlinge werden ihm täglich begegnet
sein, bei seinem Gang zwischen seinem Haus am Fuße des Petersbergs und seiner
Pfarrkirche, Allerheiligen. Auch dort hielten sie sich ”in den verwuesten hause
undt keller unter Sancti Severi kirchen” am Domhügel „erbärmlich“ auf.<a href="#_edn81" name="_ednref81" >[81]</a></p>

<p align="justify">In seinem „Diarium“ und dem „Ohnvorgreifliche[n] Bedencken“ gibt Marx
Zeugnis von sich selbst als einer verantwortlichen, pflichtbewussten
Amtsperson. Der Leser dieser Schriften erblickt drei Facetten bei Marx, die
hier abschliessend festgehalten werden sollen.</p>

<p align="justify">Erstens: Marx, der Pastor. Die eben zitierten Einträge
bringen das karitative Gewissen des Autors zum Ausdruck. Er sorgte sich um die
Armen. Marx zeigt, wie er versucht, das Ideal eines Priesters zu erfüllen.
Durch Schulunterricht und Kinderlehre, durch das Spenden der Sakramente und
durch die Lesung von Messen sorgte dieser Hirte weiterhin, unter schwierigen
Bedingungen, für das Seelenheil seiner Gemeinde.<a href="#_edn82" name="_ednref82" >[82]</a></p>

<p align="justify">Zweitens: Marx, der Dekan der katholisch-theologischen
Fakultät. Mit seinen lutherischen Kontrahenten ging Marx recht respektvoll um.
In dieser Hinsicht folgte er nicht seinem Mainzer Lehrer, Adam Contzen.<a
href="#_edn83" name="_ednref83" >[83]</a>
Doch bei Rennemanns posthumer Darstellung von Marx als eines umgänglichen
Kollegen ist Vorsicht geboten. Marx’ „Ohnvorgreifliches Bedencken“ unterschied
selbst zwischen den ‘alten’ und den ‘neuen’ lutherischen Professoren, die ab
1632 an der Universität eintrafen.</p>

<p align="justify">Drittens: Marx, der Stiftsgeistliche. Das Tagebuch will
vor allem zeigen, wie Marx vehement die Rechte seines Stiftes verteidigt. Die
zurückhaltende Art, in welcher Marx bei solchen Berichten über sich selbst
schreibt, sollte den ins Auge gefassten katholischen Leser wohl davon
überzeugen, dass der Autor unparteiisch Bericht erstattete. Wer heute das
Tagebuch liest, um mehr über den Autor und das Leben des katholischen Klerus in
Erfurt zur Zeit des Dreißigjährigen Krieges zu erfahren, sollte dies bei der
Lektüre bedenken.</p>


